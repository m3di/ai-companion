/**
 * THE HARVEST LAYER (round 6 step 1, docs/history/BRAIN.md §3.12).
 *
 * The system only ever knew the work that came through Telegram. Most of
 * Mehdi's real work happens in local Claude Code sessions — 67 in a week
 * across 14 project dirs, five of which the knowledge tree had never heard
 * of. This layer gives it eyes on that half, WITHOUT reading transcripts:
 *
 *   - An agent never sees a transcript. Parsing extracts a SKELETON: the
 *     opening title, a TIMELINE of the user's prompts interleaved with the
 *     milestones the work actually reached (branches, pushes, PRs), the work
 *     anchors named along the way, and the closing text. Measured: a 620KB
 *     session skeletonises to ~1-3k chars. Step 2 distils skeletons; the body
 *     stays on disk. A long burst wanders across topics, so the beats in order
 *     — not the one-line title — are what carry the arc.
 *   - THE UNIT IS THE EPISODE, NOT THE SESSION. Mehdi leaves sessions open
 *     for days (one Core-API session spans 14 days with 126h gaps between
 *     bursts), so "session ended" never fires and a session-level recap is
 *     permanently stale. An episode is a contiguous burst bounded by an idle
 *     gap; it closes on idle, is immutable once closed, and is dated to the
 *     day it happened — which is the question actually being asked.
 *
 * Deterministic and re-runnable: episodes are keyed (session_id, seq) and
 * upserted, so re-harvesting a file is idempotent.
 */

const PROJECTS_DIR = join(homedir(), '.claude', 'projects');

/** Idle gap that closes an episode. Measured across real transcripts: gaps
 *  are either under an hour (thinking/reading) or over 3.4h (walked away),
 *  so the boundary is not delicate. */
const EPISODE_GAP_MS = 2 * 60 * 60 * 1000;

/** A burst must be at least this long to be worth remembering — filters out
 *  a session opened and abandoned in seconds. */
const MIN_EPISODE_MS = 60 * 1000;

// Budget split, deliberately asymmetric. Mehdi's own prompts are the highest
// signal in the record — they carry intent, corrections, and constraints that
// nothing else states ("ok now lets make pr for the first task i mean 2764",
// "we assume they give us registration events like a normal push event"). The
// agent's narration says what HAPPENED; the prompts say what was WANTED. So
// prompts get room and narration stays tight. Measured headroom: the median
// skeleton was 5.2k of a 12k budget at PROMPT_CAP 300, so this is close to
// free. Breadth still beats depth — every beat survives, clipped, and the
// transcript holds the rest.
const SKELETON_CAP = 14000;
const PROMPT_CAP = 900;
const NARRATION_CAP = 240;
const OUTCOME_CAP = 600;
/** When an episode has more beats than the cap allows, keep the OPENING and
 *  the ENDING and drop the middle — the whole complaint that started this is
 *  that a burst ends somewhere different from where it began. */
const MAX_BEATS = 60;
const MAX_FILES = 25;

/** Text that ARRIVES as a user message but is not the user talking: agent
 *  notifications, slash-command plumbing, injected reminders, bash-mode echo.
 *  In one real 267-event session, 10 of 13 string-content "user" messages were
 *  <task-notification> — unfiltered, they would drown the actual prompts. The
 *  tag list is the full set found across the corpus, not a guess. */
const NOT_USER_TEXT =
  /^\s*<(task-notification|task-id|tool-use-id|summary|status|output-file|result|usage|note|event|system-reminder|local-command-|command-name|command-message|command-args|bash-input|bash-stdout|user-prompt-submit-hook)\b/;

/** Machine-authored prose that also arrives as a plain user message: the
 *  summary injected when a session compacts, pasted slash-command output, and
 *  bare slash commands. All three were polluting real sessions. */
const NOT_USER_PROSE = [
  /^This session is being continued from a previous conversation/i,
  /^Caveat: The messages below were generated by the user while running local commands/i,
  /^##\s*Context Usage/i,
  /^\/[a-z][a-z-]*\s*$/i,
];

/** Milestones worth remembering, read off the commands the agent actually ran.
 *  These are what turn "a question" into "a question that became task 2764 and
 *  a PR" — the arc a session title never captures. */
const MILESTONES: Array<{ re: RegExp; kind: string }> = [
  { re: /gh\s+pr\s+create\b[^\n]*?(?:--title\s+["']([^"']{0,80}))?/, kind: 'opened PR' },
  { re: /gh\s+pr\s+merge\s+(\d+)?/, kind: 'merged PR' },
  { re: /git\s+push\s+(?:-u\s+)?origin\s+([^\s;&|]+)/, kind: 'pushed branch' },
  { re: /git\s+(?:checkout\s+-b|switch\s+-c)\s+([^\s;&|]+)/, kind: 'new branch' },
  { re: /git\s+commit\b/, kind: 'commit' },
];

/** Assistant text that narrates nothing: harness notices, refusals to speak,
 *  and the session-limit banner (which repeated 8 times in one real session).
 *  A limit banner is still signal — it means the work was CUT SHORT, not
 *  finished — so it is recorded as a milestone rather than silently dropped. */
const NARRATION_NOISE =
  /^(You've hit your session limit|No response requested\.?$|\(no content\)|API Error)/i;

/** Work anchors named in prose: Fibery task/bug ids, PR refs, branches, hosts.
 *  Deliberately conservative — a bare 4-digit number matches years and ports,
 *  so an id only counts when it is labelled or prefixed. */
function extractEntities(text: string): string[] {
  const out = new Set<string>();
  for (const m of text.matchAll(/\btask\/([a-z0-9][a-z0-9-]{2,60})/gi)) out.add(`branch:task/${m[1]}`);
  for (const m of text.matchAll(/#(\d{2,5})\b/g)) out.add(`ref:#${m[1]}`);
  for (const m of text.matchAll(/\b(task|bug|request|ticket)\s+#?(\d{2,5})\b/gi)) {
    out.add(`${(m[1] ?? '').toLowerCase()}:${m[2] ?? ''}`);
  }
  for (const m of text.matchAll(/https?:\/\/([a-z0-9.-]+)(\/[^\s)"']*)?/gi)) {
    out.add(`url:${m[1]}${(m[2] ?? '').split('/').slice(0, 3).join('/')}`);
  }
  return [...out];
}

export interface Episode {
  sessionId: string;
  seq: number;
  project: string;
  cwd: string;
  gitBranch: string | null;
  startedAt: string;
  endedAt: string;
  turns: number;
  userPrompts: number;
  tools: Record<string, number>;
  files: string[];
  milestones: Array<{ at: string; kind: string; detail?: string }>;
  entities: string[];
  title: string | null;
  skeleton: string;
  closed: boolean;
  /** Harvested and searchable, but never summarised. */
  distillable: boolean;
  /** Summarised, but never folded into the knowledge tree by the operator. */
  foldable: boolean;
  /** uuid of the episode's first event — stable ACROSS session forks, so the
   *  same real work resumed into a new session id dedupes to one episode. */
  anchor: string | null;
  /** The transcript's entrypoint ('cli', 'sdk-ts', …); null on old transcripts
   *  that predate the field, which are treated as typed. */
  entrypoint: string | null;
}

/** False when a PROGRAM drove the session (config.noHarvestEntrypoints), the
 *  episode ran in the operator's knowledge dir, or its project is on Mehdi's
 *  do-not-watch list. A transcript without an entrypoint is treated as typed:
 *  the silent failure to avoid is dropping HIS work, not keeping a program's. */
export function harvestable(ep: Pick<Episode, 'cwd' | 'project' | 'entrypoint'>, kb = knowledgePath()): boolean {
  const entry = (ep.entrypoint ?? '').toLowerCase();
  if (entry && config.noHarvestEntrypoints.some((p) => (p.endsWith('*') ? entry.startsWith(p.slice(0, -1)) : entry === p))) return false;
  if (ep.cwd.startsWith(kb)) return false;
  return !config.noHarvestProjects.has(ep.project.toLowerCase());
}

interface Line {
  type?: string;
  uuid?: string;
  prNumber?: number;
  prUrl?: string;
  prRepository?: string;
  timestamp?: string;
  cwd?: string;
  gitBranch?: string;
  /** Who drove the session: 'cli' | 'claude-desktop' | 'sdk-ts' | 'sdk-py' | … */
  entrypoint?: string;
  isSidechain?: boolean;
  aiTitle?: string;
  message?: { content?: unknown; role?: string };
}

/** Real user prose, or undefined if this line is plumbing/tool traffic. */
function userText(l: Line): string | undefined {
  if (l.type !== 'user' || l.isSidechain) return undefined;
  const c = l.message?.content;
  if (typeof c !== 'string') return undefined; // arrays are tool_result traffic
  const t = c.trim();
  if (!t || NOT_USER_TEXT.test(t)) return undefined;
  if (NOT_USER_PROSE.some((re) => re.test(t))) return undefined;
  return t;
}

/** Bash commands an assistant line ran, for milestone detection. */
function bashCommands(l: Line): string[] {
  if (l.type !== 'assistant' || l.isSidechain) return [];
  const c = l.message?.content;
  if (!Array.isArray(c)) return [];
  return c
    .filter((b: { type?: string; name?: string }) => b?.type === 'tool_use' && b.name === 'Bash')
    .map((b: { input?: { command?: string } }) => b.input?.command ?? '')
    .filter(Boolean);
}

/** The assistant's own narration — the substrate that makes summarising cheap.
 *  Measured on a 1.5MB session: 37 text blocks, 14,001 chars = 0.9% of the
 *  file, already written as prose describing the work as it happened ("Config
 *  matrix is done. Six deep-dive agents still running — I'll assemble…").
 *  This is what carries an episode whose USER barely typed: an arc built from
 *  prompts alone degrades exactly where the agent worked autonomously, which
 *  is where the interesting work is. */
function assistantText(l: Line): string | undefined {
  if (l.type !== 'assistant' || l.isSidechain) return undefined;
  const c = l.message?.content;
  if (!Array.isArray(c)) return undefined;
  const text = c
    .filter((b: { type?: string; text?: string }) => b?.type === 'text' && b.text)
    .map((b: { text?: string }) => b.text!.trim())
    .join('\n')
    .trim();
  return text || undefined;
}

function toolUses(l: Line): Array<{ name: string; path?: string }> {
  if (l.type !== 'assistant' || l.isSidechain) return [];
  const c = l.message?.content;
  if (!Array.isArray(c)) return [];
  return c
    .filter((b: { type?: string }) => b?.type === 'tool_use')
    .map((b: { name?: string; input?: { file_path?: string; path?: string } }) => ({
      name: b.name ?? '?',
      path: b.input?.file_path ?? b.input?.path,
    }));
}

/** Split one transcript into episodes on idle gaps. */
export function segmentFile(path: string, now = Date.now()): Episode[] {
  const raw = readFileSync(path, 'utf8');
  const sessionId = basename(path, '.jsonl');

  const lines: Line[] = [];
  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    try {
      lines.push(JSON.parse(line) as Line);
    } catch {
      // A transcript being appended to can end mid-line; skip it.
    }
  }
  if (!lines.length) return [];

  // Claude Code writes ONE title per session, early, and never revisits it
  // (verified across the corpus: every session has exactly one distinct
  // ai-title). So this is where the session STARTED, not what it became — a
  // burst that opens with a question and ends in a merged PR still carries the
  // question as its title. Hence the timeline below.
  const title = lines.filter((l) => l.type === 'ai-title' && l.aiTitle).pop()?.aiTitle ?? null;
  const cwd = lines.find((l) => l.cwd)?.cwd ?? '';
  const project = cwd ? basename(cwd) : basename(join(path, '..')).replace(/^-/, '');
  const entrypoint = lines.find((l) => l.entrypoint)?.entrypoint ?? null;

  const timed = lines.filter((l) => l.timestamp);
  if (!timed.length) return [];

  const episodes: Episode[] = [];
  let bucket: Line[] = [];
  let prev = 0;

  const flush = (): void => {
    if (!bucket.length) return;
    const stamps = bucket.map((l) => Date.parse(l.timestamp!)).filter(Number.isFinite);
    if (!stamps.length) {
      bucket = [];
      return;
    }
    const start = Math.min(...stamps);
    const end = Math.max(...stamps);

    const prompts: Array<{ at: string; stamp: string; text: string }> = [];
    const narration: Array<{ at: string; text: string }> = [];
    const prs = new Set<string>();
    const milestones: Array<{ at: string; stamp?: string; kind: string; detail?: string }> = [];
    const entities = new Set<string>();
    const tools: Record<string, number> = {};
    const files = new Set<string>();
    let turns = 0;
    let lastAssistant = '';
    let branch: string | null = null;

    for (const l of bucket) {
      if (l.gitBranch && !branch) branch = l.gitBranch;
      const stamp = l.timestamp ?? '';
      const clock = stamp.slice(11, 16);
      const u = userText(l);
      if (u) {
        prompts.push({ at: clock, stamp, text: u.slice(0, PROMPT_CAP) });
        for (const e of extractEntities(u)) entities.add(e);
      }
      const a = assistantText(l);
      if (a) {
        turns += 1;
        lastAssistant = a;
        if (NARRATION_NOISE.test(a)) {
          // A session-limit banner means the work was cut short, not finished.
          if (/^You've hit your session limit/i.test(a) && !milestones.some((m) => m.kind === 'hit session limit')) {
            milestones.push({ at: clock, kind: 'hit session limit' });
          }
        } else {
          narration.push({ at: stamp, text: a.replace(/\s+/g, ' ').slice(0, NARRATION_CAP) });
        }
      }
      // Claude Code records PRs explicitly — exact, and better than parsing
      // them back out of shell commands.
      if (l.type === 'pr-link' && l.prNumber) {
        const ref = `${(l.prRepository ?? '').split('/').pop() ?? ''}#${l.prNumber}`;
        if (!prs.has(ref)) {
          prs.add(ref);
          milestones.push({ at: clock, kind: 'PR', detail: ref });
          entities.add(`pr:${ref}`);
        }
      }
      for (const cmd of bashCommands(l)) {
        for (const { re, kind } of MILESTONES) {
          const m = re.exec(cmd);
          if (!m) continue;
          const detail = (m[1] ?? '').trim() || undefined;
          // Commits repeat constantly; keep one marker per episode for them,
          // but every branch/PR event is its own beat in the arc.
          if (kind === 'commit' && milestones.some((x) => x.kind === 'commit')) continue;
          milestones.push({ at: clock, stamp, kind, detail });
          if (detail) for (const e of extractEntities(detail)) entities.add(e);
          break;
        }
      }
      for (const t of toolUses(l)) {
        tools[t.name] = (tools[t.name] ?? 0) + 1;
        if (t.path) files.add(t.path);
      }
    }

    // ATTENDED WORK MEANS THE HUMAN TYPED. An episode with no real user prose
    // is not Mehdi at a terminal — it is the bot's own fleet. Worker sessions
    // run with cwd defaulting to the bot's workingDir, so they land under the
    // ai-companion project dir and look local; their prompts arrive through the
    // SDK rather than as typed prose. Excluding by session id catches only the
    // ids still in `sessions` (a /new rotates them out), which left 60 of 188
    // episodes — "Fix affiliate-app Dependabot dependency upgrades", "Prepare
    // Northwind Pay meeting brief" — being read back as his own work. The fleet's
    // work is already tracked as threads; double-counting it would let the
    // system treat its own output as evidence of his activity.
    const worked = prompts.length > 0;
    if (end - start >= MIN_EPISODE_MS && worked) {
      // A TIMELINE, not a blob. A long burst wanders — one real session titled
      // "Evaluate Temporal…" ran 10 hours through a stacked PR, a planning doc,
      // task 2764's PR, a settings change and a launchpad cron fix. The title
      // names only where it STARTED (Claude Code sets it once and never
      // revisits it), so the prompts interleaved with the milestones are what
      // carry the arc. Deciding where one topic ends is step 2's judgment call;
      // step 1's job is to hand it the beats in order.
      // Three kinds of beat on ONE clock: what Mehdi asked, what the agent
      // narrated doing, and what actually landed. Ordered by full timestamp —
      // HH:MM alone scrambles any episode crossing midnight, and several do.
      const raw = [
        ...prompts.map((p) => ({ stamp: p.stamp, line: `[${p.at}] ASKED: ${p.text}` })),
        ...narration.map((n) => ({ stamp: n.at, line: `[${n.at.slice(11, 16)}] DID: ${n.text}` })),
        ...milestones.map((m) => ({
          stamp: m.stamp ?? '',
          line: `[${m.at}] >> ${m.kind}${m.detail ? ` — ${m.detail}` : ''}`,
        })),
      ].sort((a, b) => a.stamp.localeCompare(b.stamp));

      // Over budget: keep the opening and the ending, say what was dropped.
      const beats =
        raw.length <= MAX_BEATS
          ? raw.map((b) => b.line)
          : [
              ...raw.slice(0, Math.floor(MAX_BEATS / 3)).map((b) => b.line),
              `… ${raw.length - MAX_BEATS} beat(s) omitted from the middle …`,
              ...raw.slice(-Math.ceil((MAX_BEATS * 2) / 3)).map((b) => b.line),
            ];

      const skeleton = [
        title ? `TITLED (how it opened, set once at the start): ${title}` : '',
        beats.length ? `TIMELINE:\n${beats.join('\n')}` : '',
        entities.size ? `TOUCHED: ${[...entities].join(', ')}` : '',
        lastAssistant && !NARRATION_NOISE.test(lastAssistant)
          ? `CLOSED WITH:\n${lastAssistant.slice(0, OUTCOME_CAP)}`
          : '',
      ]
        .filter(Boolean)
        .join('\n\n')
        .slice(0, SKELETON_CAP);

      // Older sessions predate ai-title entirely. The field means "opened as",
      // and the first thing the user typed IS how it opened — a far better
      // label than "(untitled)".
      const label =
        title ?? (prompts[0] ? prompts[0].text.split('\n')[0]!.slice(0, 70) : null);

      episodes.push({
        sessionId,
        seq: episodes.length,
        project,
        cwd,
        gitBranch: branch,
        startedAt: new Date(start).toISOString().replace('T', ' ').slice(0, 19),
        endedAt: new Date(end).toISOString().replace('T', ' ').slice(0, 19),
        turns,
        userPrompts: prompts.length,
        tools,
        files: [...files].slice(0, MAX_FILES),
        milestones,
        entities: [...entities],
        distillable: !config.noDistillProjects.has(project.toLowerCase()),
        foldable: !config.noFoldProjects.has(project.toLowerCase()),
        anchor: bucket.find((l) => l.uuid)?.uuid ?? null,
        entrypoint,
        title: label,
        skeleton,
        closed: now - end > EPISODE_GAP_MS,
      });
    }
    bucket = [];
  };

  for (const l of timed) {
    const ts = Date.parse(l.timestamp!);
    if (!Number.isFinite(ts)) continue;
    if (prev && ts - prev > EPISODE_GAP_MS) flush();
    bucket.push(l);
    prev = ts;
  }
  flush();
  return episodes;
}

/** Every transcript on disk, excluding subagent sidechains. */
function transcriptFiles(): string[] {
  if (!existsSync(PROJECTS_DIR)) return [];
  const out: string[] = [];
  const walk = (dir: string, depth = 0): void => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      // A subagent's transcript is part of its parent's work, not a separate
      // episode of Mehdi's.
      if (e.isDirectory() && e.name !== 'subagents' && depth < 2) walk(p, depth + 1);
      else if (e.isFile() && e.name.endsWith('.jsonl')) out.push(p);
    }
  };
  walk(PROJECTS_DIR);
  return out;
}

export interface HarvestResult {
  filesScanned: number;
  filesSkipped: number;
  episodes: number;
  excluded: number;
  deduped: number;
}

/**
 * Harvest every local transcript into the `episodes` table.
 *
 * Excludes the bot's OWN sessions — its workers already exist as threads, and
 * counting them as Mehdi's work would let the system read its own output back
 * as evidence of his activity. Also excludes the operator's runs, whose cwd is
 * the knowledge dir.
 */
export function harvestAll(opts: { force?: boolean } = {}): HarvestResult {
  const botIds = botSessionIds();
  const kb = knowledgePath();
  const res: HarvestResult = { filesScanned: 0, filesSkipped: 0, episodes: 0, excluded: 0, deduped: 0 };

  for (const path of transcriptFiles()) {
    const sessionId = basename(path, '.jsonl');
    if (botIds.has(sessionId)) {
      res.excluded += 1;
      continue;
    }
    const st = statSync(path);
    const mtime = Math.floor(st.mtimeMs);
    if (!opts.force) {
      const seen = fileHarvestState(path);
      // Unchanged since the last pass — its closed episodes are immutable.
      if (seen && seen.mtime === mtime && seen.size === st.size) {
        res.filesSkipped += 1;
        continue;
      }
    }
    res.filesScanned += 1;
    // seq is the segment's POSITION IN THE FILE, not a count of what was kept:
    // a skipped segment leaves a hole, so the rows after it keep their key
    // (and their id, and their recap) instead of sliding into a neighbour's.
    const segments = segmentFile(path);
    segments.forEach((ep, seq) => {
      if (!harvestable(ep, kb)) {
        res.excluded += 1;
        return;
      }
      // A forked transcript shares anchors with its parent. The copy that is
      // already held — and possibly already distilled — stays; this one is
      // never inserted, so there is nothing for the dedupe to delete and
      // nothing for the distiller to summarise twice (design proposal #2).
      if (anchorOwnedElsewhere(ep.anchor, ep.sessionId)) {
        res.deduped += 1;
        return;
      }
      upsertEpisode({ ...ep, seq });
      res.episodes += 1;
    });
    // Upsert alone never removes: if a filter or threshold change makes a file
    // yield FEWER episodes than last time, the surplus rows would linger as
    // phantom work. Drop anything past the new tail (no segments clears it).
    dropEpisodesFrom(basename(path, '.jsonl'), segments.length);
    markFileHarvested(path, mtime, st.size);
  }
  res.deduped += dedupeEpisodes();
  return res;
}
